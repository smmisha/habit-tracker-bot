def _T(key: str, lang: str = "ru", **kwargs) -> str:
    """Helper to translate a key with optional formatting arguments"""
    safe_lang = lang if lang in ["ru", "en", "uk"] else "ru"
    entry = TRANSLATIONS.get(key, {})
    val = entry.get(safe_lang, entry.get("ru", key))
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            pass
    return val
